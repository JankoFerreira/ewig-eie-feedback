import assert from 'node:assert/strict';
import { initialBudget, totals, forecast, validateBudget, paidFor } from './model.ts';
const b = initialBudget();
b.opening=20000;b.reserve=2000;b.targetDate='2027-03-20';
b.expenses=[{id:'venue',name:'Venue',category:'Wedding',supplier:'Venue',amount:30000,due:'2027-02-01',notes:''},{id:'trip',name:'Trip',category:'Honeymoon',supplier:'',amount:10000,due:'',notes:''}];
b.payments=[{id:'p',expenseId:'venue',amount:5000,date:'2026-11-11',by:'Partner'}];
b.contributions=[{id:'c',name:'Received',amount:1000,date:'2026-11-11',received:true},{id:'future',name:'Planned',amount:20000,date:'2027-03-01',received:false},{id:'late',name:'Late',amount:90000,date:'2027-04-01',received:false}];
assert.equal(validateBudget(b),true);
assert.deepEqual(totals(b),{allocated:40000,paid:5000,received:1000,planned:20000,available:16000,outstanding:35000,final:-1000,free:-21000});
assert.equal(paidFor(b,'venue'),5000);
assert.deepEqual(forecast(b).map(e=>e.balance),[-9000,11000]);
const received=structuredClone(b);received.contributions[1].received=true;
assert.equal(totals(received).final,totals(b).final);
assert.equal(totals(received).available,36000);
const invalid=structuredClone(b);invalid.payments[0].amount=30001;assert.equal(validateBudget(invalid),false);
const orphan=structuredClone(b);orphan.payments[0].expenseId='missing';assert.equal(validateBudget(orphan),false);
const duplicate=structuredClone(b);duplicate.contributions.push(duplicate.contributions[0]);assert.equal(validateBudget(duplicate),false);
const badDate=structuredClone(b);badDate.targetDate='2027-02-30';assert.equal(validateBudget(badDate),false);
assert.equal(validateBudget({}),false);
assert.equal(validateBudget(null),false);
assert.equal(validateBudget(JSON.parse(JSON.stringify(b))),true);
const decimals=initialBudget();decimals.opening=.3;decimals.expenses=[{...b.expenses[0],amount:.1},{...b.expenses[1],amount:.2}];assert.equal(totals(decimals).free,0);
const noDeadline=structuredClone(b);noDeadline.targetDate='';assert.equal(totals(noDeadline).planned,0);
console.log('Budget checks passed: totals, received/planned accounting, deadline, cash-flow shortfalls, money rounding, backup validation and overpayments.');
